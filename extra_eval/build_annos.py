#!/usr/bin/env python3
"""Set up ``annotations/`` and ``scripts/extra_eval_config.py`` for ``run_extra_eval.sh``.

* Links every file of Chat-Scene's HF ``annotations/`` release (``--official_dir``) into
  ``annotations/``. Chat-Scene's scorers (``utils/eval.py``) read some of them from that
  fixed relative path. Existing entries are left alone.
* Converts Real-3DQA (``debiased_test`` and ``rotation_{0,90,180,270}``) to Chat-Scene's
  SQA3D val format as ``annotations/real3dqa_<split>.json``:
  prompt = ``<situation> <question> Answer the question using a single word or phrase.``,
  ``sqa_type`` = the question's first word (What/Is/How/Can/Which/other = 0..5), as in
  ``sqa3d_test.json``, and ``qid`` = Real-3DQA ``question_id``. The rotation splits differ
  only in the situation text, so the scene input is the same as for SQA3D.
* Writes ``scripts/extra_eval_config.py`` = ``scripts/config.py`` plus one
  ``val_file_dict`` entry ``real3dqa_<split>`` per split. These entries use the same Mask3D
  feature and attribute files as Chat-Scene's ``sqa3d_test``.
"""

import argparse
import json
import os

REAL3DQA_SPLITS = ["debiased_test", "rotation_0", "rotation_90", "rotation_180", "rotation_270"]
QA_SUFFIX = " Answer the question using a single word or phrase."
SQA_TYPE = {"what": 0, "is": 1, "how": 2, "can": 3, "which": 4}


def link_official(official_dir, anno_dir):
    for name in sorted(os.listdir(official_dir)):
        dst = os.path.join(anno_dir, name)
        if not os.path.lexists(dst):
            os.symlink(os.path.abspath(os.path.join(official_dir, name)), dst)


def convert_real3dqa(real3dqa_dir, anno_dir):
    for split in REAL3DQA_SPLITS:
        out = []
        for line in open(os.path.join(real3dqa_dir, f"{split}.jsonl")):
            x = json.loads(line)
            q = x["question"].strip()
            out.append({
                "scene_id": x["scene_id"],
                "obj_id": 0,
                "prompt": f'{x["situation"].strip()} {q}{QA_SUFFIX}',
                "ref_captions": [x["answer"]],
                "sqa_type": SQA_TYPE.get(q.split(" ")[0].lower(), 5),
                "qid": str(x["question_id"]),
                "question_type": x["question_type"],
            })
        json.dump(out, open(os.path.join(anno_dir, f"real3dqa_{split}.json"), "w"), indent=1)
        print(f"real3dqa_{split}: {len(out)}")


def write_config(config_out):
    lines = ["\n\n# ---- Real-3DQA (generated by extra_eval/build_annos.py) ----"]
    for split in REAL3DQA_SPLITS:
        lines.append(f"val_file_dict['real3dqa_{split}'] = val_file_dict['sqa3d_test'][:3] + "
                     f"[f'{{anno_root}}/real3dqa_{split}.json']")
    open(config_out, "w").write(open("scripts/config.py").read() + "\n".join(lines) + "\n")
    print(f"config -> {config_out}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--official_dir", required=True, help="Chat-Scene HF annotations/ dir")
    ap.add_argument("--real3dqa_dir", required=True, help="dir with Real-3DQA <split>.jsonl")
    ap.add_argument("--anno_dir", default="annotations")
    ap.add_argument("--config_out", default="scripts/extra_eval_config.py")
    args = ap.parse_args()
    os.makedirs(args.anno_dir, exist_ok=True)
    link_official(args.official_dir, args.anno_dir)
    convert_real3dqa(args.real3dqa_dir, args.anno_dir)
    write_config(args.config_out)


if __name__ == "__main__":
    main()
